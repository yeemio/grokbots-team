#!/usr/bin/env bash
# board-report.sh — compact markdown table from board/status.json
#
# Usage:
#   ./board-report.sh           # stdout only
#   ./board-report.sh --write   # also write board/STATUS.md

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
PKG_ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
BOARD="$PKG_ROOT/board/status.json"
OUT_MD="$PKG_ROOT/board/STATUS.md"
WRITE=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --write) WRITE=1; shift ;;
    -h|--help)
      sed -n '2,7p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "Unknown arg: $1" >&2
      exit 1
      ;;
  esac
done

if [[ ! -f "$BOARD" ]]; then
  echo "Missing board: $BOARD" >&2
  exit 1
fi

render() {
  if command -v jq >/dev/null 2>&1; then
    jq -r '
      def trunc(n):
        if . == null then ""
        else (tostring) as $s
          | if ($s | length) > n then $s[0:n-1] + "…" else $s end
        end;
      (
        [
          "| id | status | title | model | session | pr | work_dir | updated_at |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"
        ]
        + map(
          "| \(.id) | \(.status) | \(.title | trunc(28)) | \(.model | trunc(12)) | \(.zcode_session | trunc(16)) | \(
            if (.pr_url // "") == "" then "—"
            else ((.pr_url | split("/") | last) as $n | "#" + $n)
            end
          ) | \((.work_dir | split("/") | last) | trunc(36)) | \(.updated_at | trunc(25)) |"
        )
      ) | .[]
    ' "$BOARD"
  else
    python3 - "$BOARD" <<'PY'
import json, sys
path = sys.argv[1]
with open(path) as f:
    rows = json.load(f)

def trunc(s, n):
    s = "" if s is None else str(s)
    return s if len(s) <= n else s[: n - 1] + "…"

print("| id | status | title | model | session | pr | work_dir | updated_at |")
print("| --- | --- | --- | --- | --- | --- | --- | --- |")
for r in rows:
    pr = r.get("pr_url") or ""
    pr_cell = "—" if not pr else "#" + pr.rstrip("/").split("/")[-1]
    wd = (r.get("work_dir") or "").rstrip("/").split("/")[-1]
    print(
        f"| {r.get('id','')} | {r.get('status','')} | {trunc(r.get('title'), 28)} | "
        f"{trunc(r.get('model'), 12)} | {trunc(r.get('zcode_session'), 16)} | "
        f"{pr_cell} | {trunc(wd, 36)} | {trunc(r.get('updated_at'), 25)} |"
    )
PY
  fi
}

REPORT=$(render)
printf '%s\n' "$REPORT"

if [[ "$WRITE" -eq 1 ]]; then
  {
    echo "# parallel-packages board"
    echo ""
    echo "Generated by \`scripts/board-report.sh --write\` (Asia/Shanghai)."
    echo ""
    printf '%s\n' "$REPORT"
    echo ""
  } > "$OUT_MD"
  echo "" >&2
  echo "wrote $OUT_MD" >&2
fi
